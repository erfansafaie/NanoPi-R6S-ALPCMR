sys.path.insert(0, str(os.getcwd()))
if str(os.getcwd()) != "/home/pi/NanoPi-R6S-ALPCMR":
    sys.path.insert(0, str(os.getcwd()) + "/NanoPi-R6S-ALPCMR")

from src.camera.camera_config import (
    CameraConfigError,
    load_camera_endpoints,
    redact_rtsp_url,
)
from src.camera.read_cam import Camera, StreamWS
from src.run import GracefulKiller, RunWorker


# ---------------------------------------------------------------------------
# MODE SWITCH: keep exactly ONE of the following three lines uncommented.
